    _write(skill / "CLAUDE.md", "# alpha provenance\n")
    _write(skill / "references" / "ref.md", "# ref\n")

    _write(root / "docs" / "guide.md", "# Guide\n\nSee other.md.\n")
    _write(root / "docs" / "generated.md", "<!-- generated by tool -->\n# Output\n")
    _write(root / "docs" / "CMakeLists.txt", "project(x)\n")

    _write(root / "ignored" / "CLAUDE.md", "# in a gitignored directory\n")
    _write(root / "ignored" / "doc.md", "# in a gitignored directory\n")
    _write(root / "tmp" / "CLAUDE.md", "# in a noise-named directory\n")

    outside = tmp_path / "outside"
    _write(outside / "CLAUDE.md", "# reached only through a link\n")
    _write(outside / "doc.md", "# reached only through a link\n")
