class TestDocumentation:
    """The documents that route to the script name what the script accepts."""

    def test_audit_lane_documents_the_real_flags(self):
        doc = (MD_DOMAIN / "references" / "lanes" / "audit-lane.md").read_text(encoding="utf-8")
        start = doc.index("## Auditing everything (`discover_all.py`)")
        section = doc[start:doc.index("## The pipeline")]
        command = re.search(r'discover_all\.py"[ ]+[\\]\n(.+)\n', section).group(1)
        documented = set(re.findall(r"--[a-z][a-z-]*", command))
