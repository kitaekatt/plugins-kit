class TestOutput:
    def test_out_writes_the_json_to_a_file(self, project, tmp_path, capsys):
        out = tmp_path / "result.json"
        assert discover_all.main(_cli(project, "--out", str(out))) == 0
        captured = capsys.readouterr()
        assert captured.out == ""
        assert set(json.loads(out.read_text(encoding="utf-8"))) >= {"lanes", "skipped", "counts", "fixMode"}

    def test_counts_go_to_stderr(self, project, capsys):
        assert discover_all.main(_cli(project)) == 0
        err = capsys.readouterr().err
        for lane in LANE_SCRIPT:
            assert f"{lane}=" in err
        assert "skipped=" in err

    def test_the_output_is_ascii_json(self, project, capsys):
        discover_all.main(_cli(project))
        capsys.readouterr().out.encode("ascii")

    def test_the_command_line_entry_point_runs(self, project):
        """The script launched as a command, in a subprocess. The guard's
        re-exec is a no-op under the suite's skip variable, and the child gets
        this process's import path so bootstrap_lib resolves as it does here."""
        env = {
            **os.environ,
            "_BOOTSTRAP_GUARD_SKIP_REEXEC": "1",
            "PYTHONPATH": os.pathsep.join(p for p in sys.path if p),
        }
        proc = subprocess.run(
            [sys.executable, str(SCRIPT), *_cli(project)],
            capture_output=True, text=True, env=env, check=False,
        )
        assert proc.returncode == 0, proc.stderr
        assert set(json.loads(proc.stdout)["lanes"]) == set(LANE_SCRIPT)


class TestArgsSatisfyTheLaneScripts:
    """Each lane's args carry every name its detect script reads."""

    @pytest.mark.parametrize("lane,script", sorted(LANE_SCRIPT.items()))
    def test_top_level_names_and_refs_are_supplied(self, project, lane, script):
        source = (WORKFLOW / script).read_text(encoding="utf-8")
        args = _build(project)["lanes"][lane]
        read_top = set(re.findall(r"\binput\.([A-Za-z]+)", source))
        missing = read_top - OPTIONAL_ARGS - set(args)
        assert not missing, f"{script} reads args {sorted(missing)} that {lane} does not supply"
        read_refs = set(re.findall(r"\brefs\.([A-Za-z]+)", source))
        missing_refs = read_refs - set(args["refs"])
        assert not missing_refs, f"{script} reads refs {sorted(missing_refs)} that {lane} does not supply"

    @pytest.mark.parametrize("lane", sorted(LANE_SCRIPT))
    def test_ref_paths_exist_or_are_the_interpreter(self, project, lane):
        for key, value in _build(project)["lanes"][lane]["refs"].items():
            assert Path(value).exists(), f"refs.{key} -> {value}"

    def test_per_file_records_carry_the_documented_fields(self, project):
        result = _build(project)
        for f in result["lanes"]["audit_skill"]["files"]:
            assert {"path", "kind", "ancestorClaudeMdPaths", "standardsPaths"} <= set(f)
            assert f["kind"] in ("skill", "skill_reference")
        for f in result["lanes"]["audit_claude_md"]["files"]:
            assert {"path", "role", "parentPath", "kind", "dimension"} <= set(f)
            assert f["role"] in ("root", "ancestor", "child", "local")
            assert f["dimension"] in ("code-directory", "classic")
        for f in result["lanes"]["audit_project_doc"]["files"]:
            assert {"path", "kind", "lines", "approx_tokens", "inbound_citations", "cited_by"} <= set(f)
        for f in result["lanes"]["audit_references"]["files"]:
            assert set(f) == {"file", "findings"}
            for finding in f["findings"]:
                assert set(finding) == {"severity", "line", "ref"}

    def test_review_and_density_are_off(self, project):
        lanes = _build(project)["lanes"]
        for lane in ("audit_skill", "audit_claude_md", "audit_project_doc"):
            assert lanes[lane]["review"] is False
        assert lanes["audit_claude_md"]["density"] is False
        json.dumps(lanes)


