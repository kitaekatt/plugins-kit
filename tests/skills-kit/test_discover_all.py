class TestStandardsAndRunConfig:
    FAKE = {
        "disabled": ["rule-x"],
        "thresholds": {},
        "standards": {
            "skill_md": ["/s/skill.md"],
            "reference_doc": ["/s/ref.md"],
            "claude_md": ["/s/claude.md"],
            "plain_md": ["/s/plain.md"],
        },
        "audit": {"fix_mode": "propose"},
        "lane_models": {
            "detect": {"declared": [], "run": [{"id": "sonnet", "effort": "low"}],
                       "dropped": [{"id": "luna", "effort": "high", "reason": "not runnable"}]},
            "classify": {"declared": [], "run": [{"id": "haiku", "effort": "low"}], "dropped": []},
        },
        "notes": ["a note"],
    }

    def test_standards_are_threaded_per_primitive(self, project, monkeypatch):
        monkeypatch.setattr(discover_all, "resolve_run_config", lambda workspace: self.FAKE)
        result = _build(project)
        skill = project / ".claude" / "skills" / "alpha"
        assert _record(result, "audit_skill", skill / "SKILL.md")["standardsPaths"] == ["/s/skill.md"]
        assert _record(result, "audit_skill", skill / "references" / "ref.md")["standardsPaths"] == ["/s/ref.md"]
        assert _record(result, "audit_claude_md", project / "CLAUDE.md")["standardsPaths"] == ["/s/claude.md"]
        assert _record(result, "audit_project_doc", project / "docs" / "guide.md")["standardsPaths"] == ["/s/plain.md"]

    def test_run_level_values_come_from_the_resolver(self, project, monkeypatch):
        monkeypatch.setattr(discover_all, "resolve_run_config", lambda workspace: self.FAKE)
        result = _build(project)
        assert result["fixMode"] == "propose"
        assert result["notes"] == ["a note"]
        for lane in ("audit_skill", "audit_claude_md", "audit_project_doc"):
            args = result["lanes"][lane]
            assert args["disabledCriteria"] == ["rule-x"]
            assert args["laneModels"] == {
                "run": [{"id": "sonnet", "effort": "low"}],
                "dropped": [{"id": "luna", "effort": "high", "reason": "not runnable"}],
            }
        classify = result["lanes"]["audit_references"]["laneModels"]
        assert classify == {"run": [{"id": "haiku", "effort": "low"}], "dropped": []}

    def test_the_real_resolver_runs_end_to_end(self, project):
        # No monkeypatching: resolve_standards.main under this interpreter.
        result = _build(project)
        assert result["fixMode"] in ("apply", "propose")
        assert result["lanes"]["audit_skill"]["disabledCriteria"] == sorted(
            result["lanes"]["audit_skill"]["disabledCriteria"]
        )
        run = result["lanes"]["audit_skill"]["laneModels"]["run"]
        assert run and all({"id", "effort"} <= set(e) for e in run)

    def test_a_resolver_failure_stops_the_run(self, project, monkeypatch, capsys):
        monkeypatch.setattr(discover_all.resolve_standards, "main", lambda argv: 1)
        assert discover_all.main(_cli(project)) == 1
        err = capsys.readouterr().err
        assert "resolve_standards.py exited 1" in err

    def test_a_missing_venv_stops_the_run(self, project, monkeypatch, capsys):
        monkeypatch.setattr(discover_all.bootstrap_guard, "plugin_venv_python", lambda *a, **k: None)
        argv = [a for a in _cli(project) if a not in ("--venv-python", sys.executable)]
        assert discover_all.main(argv) == 1
        assert "venv interpreter does not exist" in capsys.readouterr().err


