def _build(root, **kwargs):
    kwargs.setdefault("user_dir", root.parent / "user-skills")
    kwargs.setdefault("plugins_dir", root.parent / "plugins")
    kwargs.setdefault("config_dir", root.parent / "harness")
    kwargs.setdefault("venv_python_override", sys.executable)
    return discover_all.build(root, **kwargs)


def _paths(result, lane):
    return {Path(f["path"]) for f in result["lanes"][lane]["files"]}


def _record(result, lane, path):
    for f in result["lanes"][lane]["files"]:
        if Path(f["path"]) == path:
            return f
    raise AssertionError(f"{path} is not a {lane} subject")


class TestLaneKeysAndSubjects:
    def test_each_lane_carries_its_subjects(self, project):
        result = _build(project)
        assert set(result["lanes"]) == set(LANE_SCRIPT)
        skill = project / ".claude" / "skills" / "alpha"
        assert _paths(result, "audit_skill") == {skill / "SKILL.md", skill / "references" / "ref.md"}
        assert _paths(result, "audit_claude_md") == {
            project / "CLAUDE.md",
            project / "sub" / "CLAUDE.md",
            project / "agents" / "AGENTS.md",
            skill / "CLAUDE.md",
        }
        assert _paths(result, "audit_project_doc") == {
            project / "docs" / "guide.md",
            project / "docs" / "generated.md",
        }

    def test_references_lane_groups_findings_by_file(self, project):
        result = _build(project)
        files = result["lanes"]["audit_references"]["files"]
        skill_md = project / ".claude" / "skills" / "alpha" / "SKILL.md"
        assert [Path(f["file"]) for f in files] == [skill_md]
        findings = files[0]["findings"]
        assert [(f["severity"], f["ref"]) for f in findings] == [("WARNING", "ghost-skill")]
        assert isinstance(findings[0]["line"], int)

    def test_a_generated_marker_doc_stays_in_the_project_doc_lane(self, project):
        # The project-doc lane audits a generated doc for provenance only; it is
        # still a subject, and discover_all must not drop it.
        assert project / "docs" / "generated.md" in _paths(_build(project), "audit_project_doc")


class TestChains:
    def test_skill_md_chain_is_nearest_first_and_excludes_itself(self, project):
        result = _build(project)
        skill = project / ".claude" / "skills" / "alpha"
        chain = [Path(p) for p in _record(result, "audit_skill", skill / "SKILL.md")["ancestorClaudeMdPaths"]]
        assert chain == [skill / "CLAUDE.md", project / "CLAUDE.md"]

    def test_a_reference_document_sees_its_skills_claude_md(self, project):
        result = _build(project)
        skill = project / ".claude" / "skills" / "alpha"
        rec = _record(result, "audit_skill", skill / "references" / "ref.md")
        assert [Path(p) for p in rec["ancestorClaudeMdPaths"]] == [skill / "CLAUDE.md", project / "CLAUDE.md"]
        assert rec["kind"] == "skill_reference"

    def test_claude_md_roles_parents_and_chains(self, project):
        result = _build(project)
        root_rec = _record(result, "audit_claude_md", project / "CLAUDE.md")
        assert (root_rec["role"], root_rec["parentPath"], root_rec["ancestorClaudeMdPaths"]) == ("root", None, [])
        sub = _record(result, "audit_claude_md", project / "sub" / "CLAUDE.md")
        assert sub["role"] == "child"
        assert Path(sub["parentPath"]) == project / "CLAUDE.md"
        assert [Path(p) for p in sub["ancestorClaudeMdPaths"]] == [project / "CLAUDE.md"]
        agents = _record(result, "audit_claude_md", project / "agents" / "AGENTS.md")
        assert Path(agents["ancestorClaudeMdPaths"][0]) == project / "CLAUDE.md"
        assert "AGENTS.md" not in " ".join(agents["ancestorClaudeMdPaths"])

    def test_project_doc_chain(self, project):
        result = _build(project)
        rec = _record(result, "audit_project_doc", project / "docs" / "guide.md")
        assert [Path(p) for p in rec["ancestorClaudeMdPaths"]] == [project / "CLAUDE.md"]

    def test_chain_stops_at_the_git_root_not_above_it(self, project):
        # A CLAUDE.md above the repository is outside the workspace.
        _write(project.parent / "CLAUDE.md", "# above the repository\n")
        result = _build(project)
        for lane in ("audit_skill", "audit_claude_md", "audit_project_doc"):
            for rec in result["lanes"][lane]["files"]:
                assert str(project.parent / "CLAUDE.md") not in rec["ancestorClaudeMdPaths"]

    def test_scanning_a_subdirectory_still_chains_up_to_the_repository_root(self, project):
        result = _build(project / "sub")
        rec = _record(result, "audit_claude_md", project / "sub" / "CLAUDE.md")
        assert rec["role"] == "child"
        assert [Path(p) for p in rec["ancestorClaudeMdPaths"]] == [project / "CLAUDE.md"]
        # the repository's own CLAUDE.md is context above the scan root, not a subject
        assert project / "CLAUDE.md" not in _paths(result, "audit_claude_md")
        assert any(
            s["path"].endswith("CLAUDE.md") and "above the scan root" in s["reason"]
            for s in result["skipped"]
        )


class TestExclusions:
    def test_pruned_directories_never_reach_a_lane(self, project):
        result = _build(project)
        every = [
            f.get("path") or f.get("file")
            for lane in result["lanes"].values() for f in lane["files"]
        ]
        for forbidden in ("ignored", "linkdir", "tmp"):
            assert not [p for p in every if forbidden in Path(p).relative_to(project).parts], forbidden

    def test_links_and_noise_names_are_reported_with_reasons(self, project):
        skipped = {(s["path"], s["reason"]) for s in _build(project)["skipped"] if s["kind"] == "directory"}
        assert ("linkdir", "link") in skipped
        assert ("tmp", "noise-name") in skipped

    def test_include_dir_opts_a_noise_name_back_in(self, project):
        result = _build(project, include_dirs=["tmp"])
        assert project / "tmp" / "CLAUDE.md" in _paths(result, "audit_claude_md")

    def test_non_doc_text_files_are_not_project_docs(self, project):
        result = _build(project)
        names = {p.name for p in _paths(result, "audit_project_doc")}
        assert "CMakeLists.txt" not in names

    def test_a_shadowed_agents_md_is_reported_not_audited(self, project):
        result = _build(project)
        assert project / "sub" / "AGENTS.md" not in _paths(result, "audit_claude_md")
        assert any(
            s["path"] == "sub/AGENTS.md" and "did not discover" in s["reason"]
            for s in result["skipped"]
        )

    def test_an_empty_lane_is_omitted_and_reported(self, tmp_path, monkeypatch):
        monkeypatch.setenv("CLAUDE_CONFIG_DIR", str(tmp_path / "config"))
        root = tmp_path / "bare"
        _write(root / "docs" / "only.md", "# only\n")
        result = _build(root)
        assert set(result["lanes"]) == {"audit_project_doc"}
        empty = {s["path"] for s in result["skipped"] if s["kind"] == "lane"}
        assert empty == {"audit_skill", "audit_claude_md", "audit_references"}


class TestOwnership:
    def test_no_path_is_in_two_lanes(self, project):
        result = _build(project)
        seen = {}
        for lane in ("audit_skill", "audit_claude_md", "audit_project_doc"):
            for f in result["lanes"][lane]["files"]:
                assert f["path"] not in seen, f"{f['path']} in {seen.get(f['path'])} and {lane}"
                seen[f["path"]] = lane

    def test_a_skill_reference_is_owned_by_the_skill_lane(self, project):
        result = _build(project)
        ref = project / ".claude" / "skills" / "alpha" / "references" / "ref.md"
        assert ref in _paths(result, "audit_skill")
        assert ref not in _paths(result, "audit_project_doc")
        assert result["counts"]["ownedByOtherLane"] >= 1

    def test_a_project_doc_the_skill_lane_owns_is_listed_as_deduplicated(self, tmp_path, monkeypatch):
        # A references/ folder the project-doc walk does not recognise by path
        # (no `skills/` segment) is still the skill's: discover_skill attributes
        # it structurally, and that lane keeps it.
        monkeypatch.setenv("CLAUDE_CONFIG_DIR", str(tmp_path / "config"))
        root = tmp_path / "odd"
        _write(root / "pack" / "SKILL.md", SKILL_MD)
        _write(root / "pack" / "references" / "detail.md", "# detail\n")
        result = _build(root)
        detail = root / "pack" / "references" / "detail.md"
        assert detail in _paths(result, "audit_skill")
        assert "audit_project_doc" not in result["lanes"]
        assert [d["path"] for d in result["deduplicated"]] == ["pack/references/detail.md"]
        assert result["deduplicated"][0]["keptBy"] == "audit_skill"

    def test_a_double_claim_with_no_rule_is_an_error(self):
        claims = discover_all.Claims()
        claims.claim("audit_skill", Path("x") / "a.md")
        claims.claim("audit_skill", Path("x") / "a.md")  # the same lane again is fine
        with pytest.raises(discover_all.OwnershipCollision, match="claimed by both"):
            claims.claim("audit_claude_md", Path("x") / "a.md")

    def test_main_exits_2_on_a_collision(self, project, monkeypatch, capsys):
        real = discover_all.discover_skill_files

        def claim_the_root_claude_md(root, include_dirs, skipped_dirs):
            found = real(root, include_dirs, skipped_dirs)
            found.append((project / "CLAUDE.md", "x", "?", "skill"))
            return found

        monkeypatch.setattr(discover_all, "discover_skill_files", claim_the_root_claude_md)
        status = discover_all.main(_cli(project))
        assert status == 2
        assert "claimed by both" in capsys.readouterr().err


