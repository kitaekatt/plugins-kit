"""discover_all.py: one command that makes md-domain's "audit everything" real.

The script runs the audit lanes' discoverers under one pruning policy and emits,
per lane, the exact Workflow `args` that lane's detect script expects. These
tests build a fixture project holding one subject of each kind plus the things
that must NOT be audited, and check the lane keys, the ancestor chains, the
exclusions, the ownership rule, the `maxConcurrent` passthrough, the failure
exits, and that every name a lane script reads from its args is supplied.
"""

